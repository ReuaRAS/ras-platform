import "server-only";

import { revalidatePath } from "next/cache";

/**
 * يُبطل ذاكرة الصفحات العامة بعد أي تعديل إداري.
 *
 * الصفحات العامة تُقدَّم من ذاكرة ISR (بدل تصييرها عند كل طلب)، لذلك يجب
 * إبلاغ Next عند تغيّر المحتوى حتى لا يبقى الزائر على نسخة قديمة حتى انتهاء
 * مدة `revalidate`. استدعاء الجذر بنوع layout يُبطل كل المسارات المتفرعة منه
 * (الرئيسية + صفحات القطاعات) في خطوة واحدة.
 */
export function revalidatePublic() {
  try {
    revalidatePath("/", "layout");
  } catch {
    // خارج سياق الطلب (مثلًا تنفيذ مباشر) — لا شيء لإبطاله.
  }
}
